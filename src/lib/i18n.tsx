type I18nContextValue = {
  language: AppLanguage;
  t: (message: string, variables?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue>({
  language: "en",
  t: (message) => message,
});

export function I18nProvider({
  language,
  children,
}: {
  language: AppLanguage;
  children: ReactNode;
}) {
  const value = useMemo<I18nContextValue>(() => {
    const t = (message: string, variables?: Record<string, string | number>) => {
      const translated = language === "en" ? message : (translations[language][message] ?? message);
      if (!variables) return translated;
      return Object.entries(variables).reduce(
        (result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)),
        translated,
      );
    };
    return { language, t };
  }, [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
